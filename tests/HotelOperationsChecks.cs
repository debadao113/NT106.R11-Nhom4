using System;
using System.Collections.Generic;
using System.Data.SqlClient;
using System.Linq;
using System.Net;
using System.Net.Sockets;
using System.Security.Cryptography;
using System.Threading.Tasks;
using System.Web.Script.Serialization;
using HotelNetworking;
using HotelServer;

class HotelOperationsChecks
{
    static string database="NT106_Test_"+Guid.NewGuid().ToString("N");
    static string master="Data Source=.;Initial Catalog=master;Integrated Security=True;Connect Timeout=5";
    static string connection="Data Source=.;Initial Catalog="+database+";Integrated Security=True;Connect Timeout=5";
    static JavaScriptSerializer serializer=new JavaScriptSerializer();
    static int Main()
    {
        try { RunAsync().GetAwaiter().GetResult(); return 0; }
        catch(Exception ex) { Console.WriteLine(ex); return 1; }
        finally
        {
            SqlConnection.ClearAllPools();
            // This exact name is generated by this test, never supplied by the caller.
            if(System.Text.RegularExpressions.Regex.IsMatch(database,"^NT106_Test_[a-f0-9]{32}$"))
                try { Sql(master,"IF DB_ID('"+database+"') IS NOT NULL BEGIN ALTER DATABASE ["+database+"] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE ["+database+"]; END"); }
                catch(Exception ex) { Console.WriteLine("Test database cleanup failed: "+ex.Message); }
        }
    }
    static object Sql(string cs,string sql,params SqlParameter[] args)
    {
        using(var c=new SqlConnection(cs)) using(var cmd=new SqlCommand(sql,c)) { c.Open(); cmd.Parameters.AddRange(args); return cmd.ExecuteScalar(); }
    }
    static void Assert(bool result,string message) { if(!result) throw new Exception(message); }
    static async Task<NetworkMessage> Send(NetworkClient c,string action,object data=null)
    { return await c.SendAsync(action,data,90000); }
    static async Task<T> Ok<T>(NetworkClient c,string action,object data=null)
    {
        var r=await Send(c,action,data); Assert(r.success==true,action+": "+r.error?.code+" "+r.error?.message);
        return serializer.ConvertToType<T>(r.data);
    }
    static CustomerRegistration Customer(int room,string name="O'Neil")
    { return new CustomerRegistration { roomid=room,cname=name,mobile=123456789,nationality="VN",gender="Male",dob="2000-01-01",idproof="ID",address="Address",checkin="2026-11-23" }; }
    static async Task RunAsync()
    {
        await HotelData.HotelDatabase.InitializeAsync(connection);
        Sql(connection,"INSERT dbo.rooms(roomNo,roomType,bed,price) VALUES('101','Single','Single',100),('102','Single','Single',100)");
        using(var hash=new Rfc2898DeriveBytes("test-password",16,210000,HashAlgorithmName.SHA256))
            Sql(connection,"INSERT dbo.staff_accounts(username,displayName,passwordHash,passwordSalt,passwordIterations) VALUES(N'test',N'Test',@h,@s,210000)",new SqlParameter("@h",hash.GetBytes(32)),new SqlParameter("@s",hash.Salt));
        var probe=new TcpListener(IPAddress.Loopback,0); probe.Start(); int port=((IPEndPoint)probe.LocalEndpoint).Port; probe.Stop();
        var server=new TcpHotelServer(connection,new TlsSettings { Enabled=false });
        server.Start(IPAddress.Loopback,port);
        try
        {
            using(var first=new NetworkClient(new TlsSettings { Enabled=false }))
            using(var second=new NetworkClient(new TlsSettings { Enabled=false }))
            {
                await first.ConnectAsync("127.0.0.1",port); await second.ConnectAsync("127.0.0.1",port);
                foreach(string action in new[]{"GET_CUSTOMERS","REGISTER_CUSTOMER","CHECKOUT_CUSTOMER","GET_EMPLOYEES","ADD_EMPLOYEE","DELETE_EMPLOYEE"})
                    Assert((await Send(first,action)).error?.code=="AUTH_REQUIRED","Unauthenticated action "+action);
                Console.WriteLine("PASS: All six business actions require authentication.");
                foreach(var client in new[]{first,second}) await Ok<StaffAccount>(client,"LOGIN",new { username="test",password="test-password" });
                var changed=new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
                second.EventReceived+=m=> { if(m.action=="CUSTOMERS_CHANGED") changed.TrySetResult(true); };
                var races=await Task.WhenAll(Send(first,"REGISTER_CUSTOMER",Customer(1)),Send(second,"REGISTER_CUSTOMER",Customer(1)));
                Assert(races.Count(r=>r.success==true)==1 && races.Count(r=>r.error?.code=="ROOM_UNAVAILABLE")==1,"Double booking race");
                Assert(await Task.WhenAny(changed.Task,Task.Delay(3000))==changed.Task,"No customer notification");
                int cid=serializer.ConvertToType<int>(races.First(r=>r.success==true).data);
                Console.WriteLine("PASS: Concurrent check-in accepts one customer and broadcasts updates.");
                var list=await Ok<List<CustomerRecord>>(first,"GET_CUSTOMERS",new { status="active",name="O'" });
                Assert(list.Count==1 && list[0].cname=="O'Neil","Parameterized apostrophe search");
                Assert((await Ok<List<CustomerRecord>>(first,"GET_CUSTOMERS",new { status="all",name="%' OR 1=1--" })).Count==0,"Search injection");
                Assert((await Send(first,"REGISTER_CUSTOMER",new { roomid=2,cname="bad" })).error?.code=="VALIDATION_ERROR","Missing input accepted");
                Assert((await Send(first,"CHECKOUT_CUSTOMER",new { cid,date="2026-11-22" })).error?.code=="VALIDATION_ERROR","Early checkout accepted");
                Console.WriteLine("PASS: Literal search and input/date validation.");
                // Force an insert failure after the room update to prove transaction rollback.
                Sql(connection,"CREATE TRIGGER dbo.TestRollback ON dbo.customer AFTER INSERT AS BEGIN IF EXISTS(SELECT 1 FROM inserted WHERE roomid=2) THROW 51000,'Test rollback',1; END");
                Assert((await Send(first,"REGISTER_CUSTOMER",Customer(2))).success==false,"Forced insert failure accepted");
                Assert(Convert.ToString(Sql(connection,"SELECT booked FROM dbo.rooms WHERE roomid=2"))=="NO","Room state leaked after rollback");
                Sql(connection,"DROP TRIGGER dbo.TestRollback");
                Console.WriteLine("PASS: Insert failure rolls back the room reservation.");
                await Ok<bool>(first,"CHECKOUT_CUSTOMER",new { cid,date="2026-11-23" });
                int next=await Ok<int>(second,"REGISTER_CUSTOMER",Customer(1,"Next guest"));
                Assert((await Send(first,"CHECKOUT_CUSTOMER",new { cid,date="2026-11-23" })).error?.code=="ALREADY_CHECKED_OUT","Duplicate checkout accepted");
                Assert(Convert.ToString(Sql(connection,"SELECT booked FROM dbo.rooms WHERE roomid=1"))=="YES","Duplicate checkout released next guest room");
                Assert((await Ok<List<CustomerRecord>>(first,"GET_CUSTOMERS",new { status="checkedout",name="" })).Count==1,"Checked-out filter");
                Console.WriteLine("PASS: Repeated checkout cannot release a newly occupied room.");
                var employee=new EmployeeRegistration { ename="Test employee",mobile=123456,gender="Male",emailid="test@example.com",username="employee",password="123" };
                int eid=await Ok<int>(first,"ADD_EMPLOYEE",employee);
                using(var employeeClient=new NetworkClient(new TlsSettings { Enabled=false }))
                {
                    await employeeClient.ConnectAsync("127.0.0.1",port);
                    Assert((await Send(employeeClient,"LOGIN",new { username="employee",password="wrong" })).error?.code=="INVALID_CREDENTIALS","Wrong employee password accepted");
                    var signedIn=await Ok<StaffAccount>(employeeClient,"LOGIN",new { username="employee",password="123" });
                    Assert(signedIn.accountType=="employee" && signedIn.employeeId==eid,"Employee login identity");
                    await Ok<List<Room>>(employeeClient,"GET_ROOMS");
                    Console.WriteLine("PASS: Employee authenticates through HotelServer and accesses shared rooms.");
                Assert((await Send(second,"ADD_EMPLOYEE",employee)).error?.code=="EMPLOYEE_EXISTS","Duplicate employee accepted");
                var employees=await Send(first,"GET_EMPLOYEES");
                Assert(employees.success==true && serializer.ConvertToType<List<EmployeeRecord>>(employees.data).Count==1,"Employee list");
                Assert(!serializer.Serialize(employees.data).Contains("password") && !serializer.Serialize(employees.data).Contains("PBKDF2"),"Hash leaked to client");
                Assert(Convert.ToString(Sql(connection,"SELECT pass FROM dbo.employee WHERE eid="+eid)).StartsWith("PBKDF2$210000$"),"Password stored in plaintext");
                await Ok<bool>(first,"DELETE_EMPLOYEE",new { eid });
                    Assert((await Send(employeeClient,"GET_ROOMS")).error?.code=="AUTH_REQUIRED","Deleted employee session remained authenticated");
                    Assert((await Send(employeeClient,"LOGIN",new { username="employee",password="123" })).error?.code=="INVALID_CREDENTIALS","Deleted employee can still login");
                }
                Assert((await Send(first,"DELETE_EMPLOYEE",new { eid })).error?.code=="NOT_FOUND","Missing employee delete accepted");
                Console.WriteLine("PASS: Employee create/list/delete, uniqueness and server-side password hashing.");
                var collision=new EmployeeRegistration { ename="Collision",mobile=12345,gender="Male",emailid="collision@example.com",username="test",password="employee-password" };
                int collisionId=await Ok<int>(first,"ADD_EMPLOYEE",collision);
                Assert((await Send(second,"LOGIN",new { username="test",password="employee-password" })).error?.code=="INVALID_CREDENTIALS","Employee password bypassed staff credentials");
                await Ok<StaffAccount>(second,"LOGIN",new { username="test",password="test-password" });
                await Ok<bool>(first,"DELETE_EMPLOYEE",new { eid=collisionId });
                Sql(connection,"INSERT dbo.employee(ename,mobile,gender,emailid,username,pass) VALUES(N'Legacy',123,N'Male',N'legacy@example.com',N'legacy',N'plaintext')");
                Assert((await Send(second,"LOGIN",new { username="legacy",password="plaintext" })).error?.code=="INVALID_CREDENTIALS","Legacy plaintext password accepted");
                Console.WriteLine("PASS: Staff username priority and rejection of legacy plaintext credentials.");
            }
        }
        finally { await server.StopAsync(); }
    }
}
