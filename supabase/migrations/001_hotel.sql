-- Run once in the Supabase SQL Editor on a NEW project.
-- No passwords, default users, or sample guest data are created here.
begin;

create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated;

create table public.profiles (
    user_id uuid primary key references auth.users(id) on delete cascade,
    email text not null,
    display_name text not null check (length(btrim(display_name)) between 1 and 100),
    role text not null check (role in ('admin', 'receptionist')),
    is_active boolean not null default true
);

create table public.rooms (
    id integer generated by default as identity primary key,
    number text not null unique check (length(btrim(number)) between 1 and 50),
    room_type text not null check (length(btrim(room_type)) between 1 and 100),
    bed text not null check (length(btrim(bed)) between 1 and 100),
    price bigint not null check (price >= 0)
);

create table public.stays (
    id integer generated by default as identity primary key,
    room_id integer not null references public.rooms(id),
    name text not null check (length(btrim(name)) between 1 and 150),
    phone text not null check (phone ~ '^\+?[0-9]{6,20}$'),
    nationality text not null default '',
    gender text not null default '',
    birth_date date,
    identity_document text not null check (length(btrim(identity_document)) between 1 and 100),
    address text not null default '',
    check_in date not null,
    check_out date,
    nightly_price bigint not null check (nightly_price >= 0),
    created_by uuid references auth.users(id) on delete set null,
    check (check_out is null or check_out >= check_in),
    check (birth_date is null or birth_date <= check_in)
);

-- Even concurrent check-ins can never occupy the same room twice.
create unique index one_active_stay_per_room on public.stays(room_id) where check_out is null;
create index stays_check_in on public.stays(check_in desc);

create table public.employees (
    id integer generated by default as identity primary key,
    name text not null check (length(btrim(name)) between 1 and 150),
    phone text not null check (phone ~ '^\+?[0-9]{6,20}$'),
    gender text not null default '',
    email text not null check (position('@' in email) > 1)
);

-- Roles come from a protected table, never from editable user_metadata.
create function private.is_staff() returns boolean
language sql stable security definer set search_path = '' as $$
    select exists(select 1 from public.profiles
        where user_id = (select auth.uid()) and is_active and role in ('admin','receptionist'));
$$;

create function private.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
    select exists(select 1 from public.profiles
        where user_id = (select auth.uid()) and is_active and role = 'admin');
$$;

alter table public.profiles enable row level security;
alter table public.rooms enable row level security;
alter table public.stays enable row level security;
alter table public.employees enable row level security;

revoke all on public.profiles, public.rooms, public.stays, public.employees from anon, authenticated;
grant select on public.profiles, public.rooms to authenticated;
grant insert on public.rooms to authenticated;
grant select, insert, delete on public.employees to authenticated;
grant usage, select on sequence public.rooms_id_seq, public.employees_id_seq to authenticated;

create policy own_profile on public.profiles for select to authenticated using (user_id = (select auth.uid()));
create policy staff_read_rooms on public.rooms for select to authenticated using ((select private.is_staff()));
create policy staff_add_rooms on public.rooms for insert to authenticated with check ((select private.is_staff()));
create policy admin_read_employees on public.employees for select to authenticated using ((select private.is_admin()));
create policy admin_add_employees on public.employees for insert to authenticated with check ((select private.is_admin()));
create policy admin_delete_employees on public.employees for delete to authenticated using ((select private.is_admin()));
-- No direct client writes to stays: use the transaction functions below.

create function public.hotel_get_rooms() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
    if not private.is_staff() then raise exception 'Tài khoản chưa được cấp quyền lễ tân.' using errcode = '42501'; end if;
    return (select coalesce(jsonb_agg(jsonb_build_object(
        'Id', r.id, 'Number', r.number, 'Type', r.room_type, 'Bed', r.bed, 'Price', r.price,
        'IsOccupied', exists(select 1 from public.stays s where s.room_id = r.id and s.check_out is null)
    ) order by r.number), '[]'::jsonb) from public.rooms r);
end;
$$;

create function public.hotel_get_customers(p_status text default 'all', p_name text default '') returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
    if not private.is_staff() then raise exception 'Tài khoản chưa được cấp quyền lễ tân.' using errcode = '42501'; end if;
    if p_status not in ('all','active','checkedout') then raise exception 'Bộ lọc không hợp lệ.'; end if;
    return (select coalesce(jsonb_agg(jsonb_build_object(
        'Id', s.id, 'RoomId', s.room_id, 'Name', s.name, 'Phone', s.phone,
        'Nationality', s.nationality, 'Gender', s.gender, 'BirthDate', s.birth_date,
        'IdentityDocument', s.identity_document, 'Address', s.address,
        'CheckIn', s.check_in, 'CheckOut', s.check_out,
        'RoomNumber', r.number, 'RoomType', r.room_type, 'Bed', r.bed, 'Price', s.nightly_price
    ) order by s.id desc), '[]'::jsonb)
    from public.stays s join public.rooms r on r.id = s.room_id
    where (p_status = 'all' or (p_status = 'active' and s.check_out is null)
        or (p_status = 'checkedout' and s.check_out is not null))
        and strpos(lower(s.name), lower(coalesce(p_name,''))) > 0);
end;
$$;

create function public.hotel_check_in(p_customer jsonb) returns integer
language plpgsql security definer set search_path = '' as $$
declare
    selected_room public.rooms;
    new_id integer;
begin
    if not private.is_staff() then raise exception 'Tài khoản chưa được cấp quyền lễ tân.' using errcode = '42501'; end if;
    select * into selected_room from public.rooms where id = (p_customer->>'RoomId')::integer for update;
    if not found then raise exception 'Phòng không tồn tại.'; end if;
    if exists(select 1 from public.stays where room_id = selected_room.id and check_out is null)
        then raise exception 'Phòng vừa được nhận. Hãy tải lại danh sách phòng.'; end if;

    insert into public.stays(room_id,name,phone,nationality,gender,birth_date,identity_document,address,check_in,nightly_price,created_by)
    values (selected_room.id, btrim(p_customer->>'Name'), p_customer->>'Phone',
        coalesce(p_customer->>'Nationality',''), coalesce(p_customer->>'Gender',''), nullif(p_customer->>'BirthDate','')::date,
        btrim(p_customer->>'IdentityDocument'), coalesce(p_customer->>'Address',''),
        (p_customer->>'CheckIn')::date, selected_room.price, auth.uid()) returning id into new_id;
    return new_id;
end;
$$;

create function public.hotel_check_out(p_stay_id integer, p_date date) returns boolean
language plpgsql security definer set search_path = '' as $$
declare selected_stay public.stays;
begin
    if not private.is_staff() then raise exception 'Tài khoản chưa được cấp quyền lễ tân.' using errcode = '42501'; end if;
    select * into selected_stay from public.stays where id = p_stay_id;
    if not found then raise exception 'Không tìm thấy lượt lưu trú.'; end if;
    -- Check-in and check-out both lock the room first to avoid deadlocks.
    perform 1 from public.rooms where id = selected_stay.room_id for update;
    select * into selected_stay from public.stays where id = p_stay_id for update;
    if selected_stay.check_out is not null then raise exception 'Khách đã trả phòng trước đó.'; end if;
    if p_date is null or p_date < selected_stay.check_in then raise exception 'Ngày trả phòng không hợp lệ.'; end if;
    update public.stays set check_out = p_date where id = p_stay_id;
    return true;
end;
$$;

revoke all on function private.is_staff(), private.is_admin() from public, anon;
grant execute on function private.is_staff(), private.is_admin() to authenticated;
revoke all on function public.hotel_get_rooms(), public.hotel_get_customers(text,text),
    public.hotel_check_in(jsonb), public.hotel_check_out(integer,date) from public, anon;
grant execute on function public.hotel_get_rooms(), public.hotel_get_customers(text,text),
    public.hotel_check_in(jsonb), public.hotel_check_out(integer,date) to authenticated;

commit;
